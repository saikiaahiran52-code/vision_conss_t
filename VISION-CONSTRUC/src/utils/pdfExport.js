import jsPDF from 'jspdf';
import 'jspdf-autotable';

export function generateBOQPdf(project) {
  const { projectName, projectType, length, width, height, numFloors, concreteGrade, results, createdAt } = project;
  const dateStr = new Date(createdAt || Date.now()).toLocaleDateString();

  const doc = new jsPDF();
  
  // Header
  doc.setTextColor('#1a56db');
  doc.setFontSize(18);
  doc.text('VISION — Construction Intelligence Platform', 14, 20);
  
  // Subtitle
  doc.setTextColor('#000000');
  doc.setFontSize(14);
  doc.text('Bill of Quantities (BOQ)', 14, 30);
  
  // Separator
  doc.setLineWidth(0.5);
  doc.line(14, 35, 196, 35);
  
  // Project Info
  doc.setFontSize(11);
  doc.text(`Project Name: ${projectName}`, 14, 45);
  doc.text(`Project Type: ${projectType}`, 14, 52);
  doc.text(`Dimensions: ${length}L × ${width}W × ${height}H (m)`, 14, 59);
  doc.text(`Floors: ${numFloors}`, 110, 45);
  doc.text(`Concrete Grade: ${concreteGrade}`, 110, 52);
  doc.text(`Date: ${dateStr}`, 110, 59);
  
  // Table
  const tableData = [
    [1, 'Concrete Volume', results.concreteVolume, 'm³'],
    [2, 'Cement', results.cement, 'bags'],
    [3, 'Steel', results.steel, 'kg'],
    [4, 'Rod Diameter', results.rodDiameter, 'mm'],
    [5, 'Sand', results.sand, 'm³'],
    [6, 'Aggregate', results.aggregate, 'm³'],
    [7, 'Bricks', results.bricks, 'nos'],
    [8, 'Water', results.waterCement, 'liters']
  ];
  
  doc.autoTable({
    startY: 70,
    head: [['Sl. No.', 'Material', 'Quantity', 'Unit']],
    body: tableData,
    theme: 'grid',
    headStyles: { fillColor: '#1a56db' }
  });
  
  // Footer
  const pageCount = doc.internal.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFontSize(9);
    doc.setTextColor(150);
    doc.text(
      `Generated by VISION • ${dateStr}`,
      doc.internal.pageSize.getWidth() / 2,
      doc.internal.pageSize.getHeight() - 10,
      { align: 'center' }
    );
  }
  
  doc.save(`VISION_BOQ_${projectName}_${dateStr.replace(/\//g, '-')}.pdf`);
}
